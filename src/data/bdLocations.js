/**
 * Get the delivery charge based on selected district and upazila
 * @param {string} district - Selected district name
 * @param {string} upazila - Selected upazila name
 * @returns {{ area: string, charge: number, label: string }}
 */
export function getDeliveryInfo(district, upazila) {
    if (district === FREE_DISTRICT && upazila === FREE_UPAZILA) {
        return { area: 'mirsarai', charge: 0, label: 'মীরসরাই — ফ্রি ডেলিভারি! 🎉' };
    }
    if (district === FREE_DISTRICT) {
        return { area: 'chattogram', charge: 100, label: 'চট্টগ্রাম জেলা — ডেলিভারি চার্জ ৳১০০' };
    }
    return { area: 'outside', charge: 150, label: 'চট্টগ্রামের বাইরে — ডেলিভারি চার্জ ৳১৫০+' };
}
